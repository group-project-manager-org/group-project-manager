-- Notify the invitee
------------------------------------------------------------------------------------------------------------
alter table public.notifications drop constraint if exists notifications_type_check;
alter table public.notifications add constraint notifications_type_check check (
  type in ('task_due_soon', 'task_overdue', 'project_due_soon', 'task_assigned', 'comment_added', 'project_invite')
);

create or replace function public.notify_project_invite() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.notifications (user_id, project_id, type, message)
  values (new.invitee_id, new.project_id, 'project_invite',
          new.inviter_name || ' invited you to join "' || new.project_name || '"');
  return new;
end $$;

drop trigger if exists project_invitations_notify on public.project_invitations;
create trigger project_invitations_notify after insert on public.project_invitations
for each row execute function public.notify_project_invite();
