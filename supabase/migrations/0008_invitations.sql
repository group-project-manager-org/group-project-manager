-- 0008_invitations.sql: owners invite people; the invitee must accept before they become a member.
-- Idempotent. Run after 0007_realtime.sql.

create table if not exists public.project_invitations (
  id                bigint generated by default as identity primary key,
  project_id        bigint not null references public.projects (id) on delete cascade,
  project_name      text not null,   -- copied: the invitee can't read the project until they accept
  invitee_id        text not null,
  invitee_name      text not null,
  invitee_image_url text,
  invited_by        text not null default public.requesting_user_id(),
  inviter_name      text not null,
  created_at        timestamptz not null default now(),
  unique (project_id, invitee_id)
);
create index if not exists project_invitations_invitee_idx on public.project_invitations (invitee_id);

revoke update on public.project_invitations from anon, authenticated;

alter table public.project_invitations enable row level security;

-- The invitee sees their invitations; the owner sees the ones pending for their project.
drop policy if exists project_invitations_select on public.project_invitations;
create policy project_invitations_select on public.project_invitations for select
  using (invitee_id = public.requesting_user_id() or public.is_project_owner(project_id));

-- Only the owner invites, and not someone who is already a member.
drop policy if exists project_invitations_insert on public.project_invitations;
create policy project_invitations_insert on public.project_invitations for insert
  with check (
    public.is_project_owner(project_id)
    and invited_by = public.requesting_user_id()
    and not exists (
      select 1 from public.project_members m where m.project_id = project_invitations.project_id and m.user_id = invitee_id
    )
  );

-- Decline (invitee) or cancel (owner).
drop policy if exists project_invitations_delete on public.project_invitations;
create policy project_invitations_delete on public.project_invitations for delete
  using (invitee_id = public.requesting_user_id() or public.is_project_owner(project_id));

-- Members now join only by accepting an invitation, so owners can no longer insert members directly.
drop policy if exists project_members_insert on public.project_members;

-- Accept: the invitee becomes a member and the invitation is removed, in one transaction.
create or replace function public.accept_invitation(p_invitation_id bigint) returns public.project_members
language plpgsql security definer set search_path = public as $$
declare
  inv public.project_invitations;
  m public.project_members;
begin
  select * into inv from public.project_invitations
  where id = p_invitation_id and invitee_id = public.requesting_user_id()
  for update;
  if not found then
    raise exception 'Invitation not found' using errcode = 'P0002';
  end if;

  insert into public.project_members (project_id, user_id, display_name, image_url, role)
  values (inv.project_id, inv.invitee_id, inv.invitee_name, inv.invitee_image_url, 'member')
  on conflict (project_id, user_id) do nothing;

  delete from public.project_invitations where id = inv.id;

  select * into m from public.project_members where project_id = inv.project_id and user_id = inv.invitee_id;
  return m;
end $$;

