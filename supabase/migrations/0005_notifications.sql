-- 0005_notifications.sql (B8): in-app notifications, assignment/comment triggers, daily due-date reminders.
-- Idempotent. Run after 0004_files.sql.

create table if not exists public.notifications (
  id         bigint generated by default as identity primary key,
  user_id    text not null,
  project_id bigint references public.projects (id) on delete cascade,
  task_id    bigint references public.tasks (id) on delete cascade,
  type       text not null check (type in ('task_due_soon', 'task_overdue', 'project_due_soon', 'task_assigned', 'comment_added')),
  message    text not null,
  read_at    timestamptz,
  created_at timestamptz not null default now(),
  dedupe_key text unique  -- reminders only: one per (type, task/project, user, day)
);
create index if not exists notifications_user_read_idx on public.notifications (user_id, read_at);

-- Clients only read their own rows and set read_at. Inserts come from the definer functions below.
revoke insert, update, delete on public.notifications from anon, authenticated;
grant update (read_at) on public.notifications to anon, authenticated;

alter table public.notifications enable row level security;

drop policy if exists notifications_select on public.notifications;
create policy notifications_select on public.notifications for select
  using (user_id = public.requesting_user_id());

drop policy if exists notifications_update on public.notifications;
create policy notifications_update on public.notifications for update
  using (user_id = public.requesting_user_id()) with check (user_id = public.requesting_user_id());

-- Display name of the caller in a project ('Someone' if unknown).
create or replace function public.actor_name(p_project_id bigint) returns text
language sql stable security definer set search_path = public as $$
  select coalesce(
    (select display_name from public.project_members
     where project_id = p_project_id and user_id = public.requesting_user_id()),
    'Someone')
$$;

------------------------------------------------------------------------------------------------------------
-- task_assigned: when assignee_id changes to someone other than the person making the change
------------------------------------------------------------------------------------------------------------
create or replace function public.notify_task_assigned() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.assignee_id is not null
     and new.assignee_id is distinct from public.requesting_user_id()
     and (tg_op = 'INSERT' or new.assignee_id is distinct from old.assignee_id)
  then
    insert into public.notifications (user_id, project_id, task_id, type, message)
    values (new.assignee_id, new.project_id, new.id, 'task_assigned',
            public.actor_name(new.project_id) || ' assigned you "' || new.title || '"');
  end if;
  return new;
end $$;

drop trigger if exists tasks_notify_assigned on public.tasks;
create trigger tasks_notify_assigned after insert or update of assignee_id on public.tasks
for each row execute function public.notify_task_assigned();

------------------------------------------------------------------------------------------------------------
-- comment_added: to the task's creator and assignee, never the commenter
------------------------------------------------------------------------------------------------------------
create or replace function public.notify_comment_added() returns trigger
language plpgsql security definer set search_path = public as $$
declare t public.tasks;
begin
  select * into t from public.tasks where id = new.task_id;
  insert into public.notifications (user_id, project_id, task_id, type, message)
  select distinct r, t.project_id, t.id, 'comment_added', new.user_name || ' commented on "' || t.title || '"'
  from unnest(array[t.created_by, t.assignee_id]) r
  where r is not null and r is distinct from new.user_id;
  return new;
end $$;

drop trigger if exists comments_notify_added on public.comments;
create trigger comments_notify_added after insert on public.comments
for each row execute function public.notify_comment_added();

------------------------------------------------------------------------------------------------------------
-- Daily reminders, called by GET /api/cron/reminders with the service key. Safe to call repeatedly:
-- dedupe_key allows one reminder per (type, task/project, user, day).
------------------------------------------------------------------------------------------------------------
create or replace function public.create_due_reminders(
  p_today date default (now() at time zone 'Australia/Sydney')::date
) returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  with candidates as (
    -- open tasks due today or tomorrow, or overdue: the assignee, else the creator
    select coalesce(t.assignee_id, t.created_by) as user_id, t.project_id, t.id as task_id,
           case when t.due_date < p_today then 'task_overdue' else 'task_due_soon' end as type,
           case when t.due_date < p_today then '"' || t.title || '" is overdue'
                when t.due_date = p_today then '"' || t.title || '" is due today'
                else '"' || t.title || '" is due tomorrow' end as message
    from public.tasks t
    where t.status <> 'done' and t.due_date is not null and t.due_date <= p_today + 1
    union all
    -- projects due within 2 days: every member
    select m.user_id, p.id, null::bigint, 'project_due_soon',
           '"' || coalesce(p.project_name, 'Your project') || '" is due ' ||
           case p.due_date - p_today when 0 then 'today' when 1 then 'tomorrow' else 'in 2 days' end
    from public.projects p
    join public.project_members m on m.project_id = p.id
    where p.due_date between p_today and p_today + 2
  )
  insert into public.notifications (user_id, project_id, task_id, type, message, dedupe_key)
  select user_id, project_id, task_id, type, message,
         type || ':' || coalesce(task_id, project_id) || ':' || user_id || ':' || p_today
  from candidates
  on conflict (dedupe_key) do nothing;
  get diagnostics n = row_count;
  return n;
end $$;

revoke execute on function public.create_due_reminders(date) from public, anon, authenticated;
grant execute on function public.create_due_reminders(date) to service_role;
