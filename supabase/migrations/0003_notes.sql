-- 0003_notes.sql (B6): shared sticky notes. Idempotent. Run after 0002_tasks.sql.

create table if not exists public.notes (
  id         bigint generated by default as identity primary key,
  project_id bigint not null references public.projects (id) on delete cascade,
  user_id    text not null default public.requesting_user_id(),
  user_name  text not null,
  content    text not null check (length(content) between 1 and 1000),
  color      text not null default 'violet' check (color in ('violet', 'gold', 'mint', 'coral')),
  pinned     boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists notes_project_idx on public.notes (project_id, pinned, created_at);

drop trigger if exists notes_set_updated_at on public.notes;
create trigger notes_set_updated_at before update on public.notes
for each row execute function public.set_updated_at();

-- Any member may (un)pin; only the author may change content or colour. RLS can't compare old and new
-- values per column, so the update policy admits members and this trigger guards the author-only columns.
create or replace function public.check_note_update() returns trigger
language plpgsql as $$
begin
  if (new.content is distinct from old.content or new.color is distinct from old.color)
     and old.user_id is distinct from public.requesting_user_id()
     and public.requesting_user_id() is not null  -- admin / SQL editor sessions are not restricted
  then
    raise exception 'Only the author can edit this note' using errcode = '42501';
  end if;
  return new;
end $$;

drop trigger if exists notes_check_update on public.notes;
create trigger notes_check_update before update on public.notes
for each row execute function public.check_note_update();

revoke update on public.notes from anon, authenticated;
grant update (content, color, pinned) on public.notes to anon, authenticated;

alter table public.notes enable row level security;

drop policy if exists notes_select on public.notes;
create policy notes_select on public.notes for select
  using (public.is_project_member(project_id));

drop policy if exists notes_insert on public.notes;
create policy notes_insert on public.notes for insert
  with check (public.is_project_member(project_id) and user_id = public.requesting_user_id());

drop policy if exists notes_update on public.notes;
create policy notes_update on public.notes for update
  using (public.is_project_member(project_id)) with check (public.is_project_member(project_id));

drop policy if exists notes_delete on public.notes;
create policy notes_delete on public.notes for delete
  using (user_id = public.requesting_user_id() or public.is_project_owner(project_id));
