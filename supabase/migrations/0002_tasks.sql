-- Idempotent. Run after 0001_core.sql.

-- Shared updated_at trigger (also used by notes in 0003).
create or replace function public.set_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

------------------------------------------------------------------------------------------------------------
-- tasks
------------------------------------------------------------------------------------------------------------
create table if not exists public.tasks (
  id              bigint generated by default as identity primary key,
  project_id      bigint not null references public.projects (id) on delete cascade,
  title           text not null check (length(title) between 1 and 200),
  description     text,
  status          text not null default 'not_started' check (status in ('not_started', 'in_progress', 'review', 'done')),
  priority        text not null default 'medium' check (priority in ('low', 'medium', 'high')),
  due_date        date,
  assignee_id     text,
  created_by      text not null default public.requesting_user_id(),
  created_by_name text not null,
  position        int not null default 0,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists tasks_project_position_idx on public.tasks (project_id, position);
create index if not exists tasks_assignee_idx on public.tasks (assignee_id);

drop trigger if exists tasks_set_updated_at on public.tasks;
create trigger tasks_set_updated_at before update on public.tasks
for each row execute function public.set_updated_at();

-- The assignee must belong to the task's project.
create or replace function public.check_task_assignee() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.assignee_id is not null and not exists (
    select 1 from public.project_members where project_id = new.project_id and user_id = new.assignee_id
  ) then
    raise exception 'assignee must be a project member' using errcode = '23514';
  end if;
  return new;
end $$;

drop trigger if exists tasks_check_assignee on public.tasks;
create trigger tasks_check_assignee before insert or update of assignee_id on public.tasks
for each row execute function public.check_task_assignee();

-- When someone leaves or is removed, unassign their tasks in that project.
create or replace function public.unassign_removed_member() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.tasks set assignee_id = null
  where project_id = old.project_id and assignee_id = old.user_id;
  return old;
end $$;

drop trigger if exists project_members_unassign on public.project_members;
create trigger project_members_unassign after delete on public.project_members
for each row execute function public.unassign_removed_member();

------------------------------------------------------------------------------------------------------------
-- subtasks
------------------------------------------------------------------------------------------------------------
create table if not exists public.subtasks (
  id         bigint generated by default as identity primary key,
  task_id    bigint not null references public.tasks (id) on delete cascade,
  title      text not null check (length(title) between 1 and 200),
  done       boolean not null default false,
  position   int not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists subtasks_task_idx on public.subtasks (task_id, position);

------------------------------------------------------------------------------------------------------------
-- comments (already exists in the live DB with no FK, no policies, nullable user_name)
------------------------------------------------------------------------------------------------------------
create table if not exists public.comments (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  task_id    bigint not null,
  user_id    text not null,
  content    text not null,
  user_name  text
);

-- No tasks table existed before this file, so any existing comment points at nothing; remove those first.
delete from public.comments c where not exists (select 1 from public.tasks t where t.id = c.task_id);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'comments_task_id_fkey') then
    alter table public.comments add constraint comments_task_id_fkey
      foreign key (task_id) references public.tasks (id) on delete cascade;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'comments_content_length') then
    alter table public.comments add constraint comments_content_length check (length(content) between 1 and 2000);
  end if;
end $$;

alter table public.comments alter column user_id set default public.requesting_user_id();
update public.comments set user_name = 'Member' where user_name is null;
alter table public.comments alter column user_name set not null;
create index if not exists comments_task_idx on public.comments (task_id, created_at);

------------------------------------------------------------------------------------------------------------
-- Column privileges: which columns UPDATE may change (RLS decides which rows)
------------------------------------------------------------------------------------------------------------
revoke update on public.tasks from anon, authenticated;
grant update (title, description, status, priority, due_date, assignee_id, position) on public.tasks to anon, authenticated;

revoke update on public.subtasks from anon, authenticated;
grant update (title, done, position) on public.subtasks to anon, authenticated;

revoke update on public.comments from anon, authenticated;

------------------------------------------------------------------------------------------------------------
-- RLS
------------------------------------------------------------------------------------------------------------
alter table public.tasks    enable row level security;
alter table public.subtasks enable row level security;
alter table public.comments enable row level security;

-- tasks: any member reads, creates and edits (the group updates status together);
-- delete is the creator or the project owner.
drop policy if exists tasks_select on public.tasks;
create policy tasks_select on public.tasks for select
  using (public.is_project_member(project_id));

drop policy if exists tasks_insert on public.tasks;
create policy tasks_insert on public.tasks for insert
  with check (public.is_project_member(project_id) and created_by = public.requesting_user_id());

drop policy if exists tasks_update on public.tasks;
create policy tasks_update on public.tasks for update
  using (public.is_project_member(project_id)) with check (public.is_project_member(project_id));

drop policy if exists tasks_delete on public.tasks;
create policy tasks_delete on public.tasks for delete
  using (created_by = public.requesting_user_id() or public.is_project_owner(project_id));

-- subtasks: a shared checklist; any member of the task's project can add, tick and remove items.
drop policy if exists subtasks_all on public.subtasks;
create policy subtasks_all on public.subtasks for all
  using (exists (select 1 from public.tasks t where t.id = task_id and public.is_project_member(t.project_id)))
  with check (exists (select 1 from public.tasks t where t.id = task_id and public.is_project_member(t.project_id)));

-- comments: members read and write; only the author deletes. No editing.
drop policy if exists comments_select on public.comments;
create policy comments_select on public.comments for select
  using (exists (select 1 from public.tasks t where t.id = task_id and public.is_project_member(t.project_id)));

drop policy if exists comments_insert on public.comments;
create policy comments_insert on public.comments for insert
  with check (
    user_id = public.requesting_user_id()
    and exists (select 1 from public.tasks t where t.id = task_id and public.is_project_member(t.project_id))
  );

drop policy if exists comments_delete on public.comments;
create policy comments_delete on public.comments for delete
  using (user_id = public.requesting_user_id());

------------------------------------------------------------------------------------------------------------
-- project_progress: share of tasks done per project (RLS of the caller applies)
------------------------------------------------------------------------------------------------------------
create or replace view public.project_progress with (security_invoker = true) as
select
  p.id as project_id,
  count(t.id)::int as task_total,
  (count(t.id) filter (where t.status = 'done'))::int as task_done,
  case when count(t.id) = 0 then 0
       else round(100.0 * count(t.id) filter (where t.status = 'done') / count(t.id))::int
  end as progress
from public.projects p
left join public.tasks t on t.project_id = p.id
group by p.id;
