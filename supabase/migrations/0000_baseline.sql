-- 0000_baseline.sql
-- Records the schema that existed before the backend work started (projects + polls).
-- On the existing database every statement is a no-op (`if not exists`); on a fresh database it creates the tables.
-- Columns match the user's information_schema export from 2026-11-14 (see supabase/README.md step 3).
-- Constraints match the user's pg_constraint export from 2026-11-14. Note: polls.project_id has NO foreign key
-- in the live database (deleting a project leaves its polls behind); 0001 cleans orphans and adds it.
--
-- ┌──────────────────────────────────────────────────────────────────────────────┐
-- │ BEFORE RUNNING 0001_core.sql: back up your current RLS policies.             │
-- │ 0001 drops and recreates policies. Run the export query in                   │
-- │ supabase/README.md (step 3) and save its output to                           │
-- │ supabase/existing_policies.sql, so the old rules are on record.              │
-- │ The raw view is: select * from pg_policies where schemaname = 'public';      │
-- └──────────────────────────────────────────────────────────────────────────────┘
--
-- This file deliberately does NOT add policies; it only records the tables (RLS was already on for all of them).
-- `comments` exists in the live database but the app doesn't use it yet. It has no FK on task_id (there is no tasks table)
-- and no policies; 0002 (B3) adds the FK, defaults and checks.

create table if not exists public.projects (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  project_name character varying,
  due_date     date,
  user_id      text default (auth.jwt() ->> 'sub')   -- Clerk user id of the creator
);

create table if not exists public.polls (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  project_id bigint,   -- no FK in the live database; added in 0001
  question   text,
  user_id    text
);

create table if not exists public.poll_options (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  poll_id     bigint references public.polls (id) on update cascade on delete cascade,
  option_name text,
  user_id     text
);

create table if not exists public.votes (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  poll_id        bigint references public.polls (id) on update cascade on delete cascade,
  poll_option_id bigint references public.poll_options (id) on update cascade on delete cascade,
  user_id        text
);

create table if not exists public.comments (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  task_id    bigint not null,
  user_id    text not null,
  content    text not null,
  user_name  text
);

alter table public.comments     enable row level security;
alter table public.projects     enable row level security;
alter table public.polls        enable row level security;
alter table public.poll_options enable row level security;
alter table public.votes        enable row level security;
