-- 0004_files.sql (B7): private `project-files` bucket, storage policies, and the `files` metadata table.
-- Idempotent. Run after 0003_notes.sql. Object paths are `{project_id}/{uuid}-{sanitised_name}`.

-- Project id from an object path; null when the first segment isn't a number (so policies fail closed).
create or replace function public.project_id_from_path(p_name text) returns bigint
language sql immutable as $$
  select case when split_part(p_name, '/', 1) ~ '^[0-9]{1,18}$' then split_part(p_name, '/', 1)::bigint end
$$;

insert into storage.buckets (id, name, public, file_size_limit)
values ('project-files', 'project-files', false, 26214400)  -- 25 MB
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit;

------------------------------------------------------------------------------------------------------------
-- Storage policies (storage.objects)
------------------------------------------------------------------------------------------------------------
drop policy if exists project_files_select on storage.objects;
create policy project_files_select on storage.objects for select
  using (bucket_id = 'project-files' and public.is_project_member(public.project_id_from_path(name)));

drop policy if exists project_files_insert on storage.objects;
create policy project_files_insert on storage.objects for insert
  with check (bucket_id = 'project-files' and public.is_project_member(public.project_id_from_path(name)));

-- Uploader (storage sets owner_id from the token's sub) or the project owner.
drop policy if exists project_files_delete on storage.objects;
create policy project_files_delete on storage.objects for delete
  using (
    bucket_id = 'project-files'
    and (owner_id = public.requesting_user_id() or public.is_project_owner(public.project_id_from_path(name)))
  );

------------------------------------------------------------------------------------------------------------
-- files metadata
------------------------------------------------------------------------------------------------------------
create table if not exists public.files (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references public.projects (id) on delete cascade,
  user_id      text not null default public.requesting_user_id(),
  user_name    text not null,
  file_name    text not null check (length(file_name) between 1 and 255),
  storage_path text not null unique,
  size_bytes   bigint not null check (size_bytes between 0 and 26214400),
  mime_type    text,
  created_at   timestamptz not null default now()
);
create index if not exists files_project_idx on public.files (project_id, created_at);

revoke update on public.files from anon, authenticated;

alter table public.files enable row level security;

drop policy if exists files_select on public.files;
create policy files_select on public.files for select
  using (public.is_project_member(project_id));

-- The row must describe an object that was really uploaded into this project's folder.
drop policy if exists files_insert on public.files;
create policy files_insert on public.files for insert
  with check (
    user_id = public.requesting_user_id()
    and public.is_project_member(project_id)
    and public.project_id_from_path(storage_path) = project_id
    and exists (select 1 from storage.objects o where o.bucket_id = 'project-files' and o.name = storage_path)
  );

drop policy if exists files_delete on public.files;
create policy files_delete on public.files for delete
  using (user_id = public.requesting_user_id() or public.is_project_owner(project_id));
